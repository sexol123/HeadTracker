def set_language(lang: str):
    global _current_lang
    if lang in _translations:
        _current_lang = lang
        log.info(f"Language set to: {lang}")
    else:
        log.warning(f"Unknown language: {lang}, falling back to en")
        _current_lang = "en"


def get_language() -> str:
    return _current_lang


def t(key: str, *args) -> str:
    s = _translations.get(_current_lang, _translations["en"]).get(key)
    if s is None:
        s = _translations["en"].get(key, key)
    if args:
        s = s.format(*args)
    return s


